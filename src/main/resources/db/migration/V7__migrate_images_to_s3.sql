-- Collections: drop the single-image column, images now live in child table
ALTER TABLE tarantula_collections DROP COLUMN featured_image_url;

-- New table: multiple images per collection entry
CREATE TABLE tarantula_collection_images (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             collection_id BIGINT NOT NULL REFERENCES tarantula_collections(id) ON DELETE CASCADE,
                                             s3_key VARCHAR(512) NOT NULL,
                                             caption VARCHAR(255),
                                             is_featured BOOLEAN NOT NULL DEFAULT FALSE,
                                             display_order INT NOT NULL DEFAULT 0,
                                             uploaded_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX idx_collection_images_collection_id ON tarantula_collection_images(collection_id);
