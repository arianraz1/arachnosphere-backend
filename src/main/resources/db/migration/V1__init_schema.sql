-- V1__init_schema.sql

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(60) NOT NULL, -- stores BCrypt hash
    profile_pic_url VARCHAR(2048),
    bio VARCHAR(1000),
    favorite_image_url VARCHAR(2048),
    favorite_caption VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP NOT NULL DEFAULT now(), -- handled in application layer
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE species_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gbif_nub_key BIGINT NOT NULL UNIQUE,
    scientific_name VARCHAR(255) NOT NULL UNIQUE,
    common_name VARCHAR(255),
    image_url VARCHAR(2048),
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE tarantula_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, -- delete all user's collections when user is deleted
    species_id BIGINT NOT NULL REFERENCES species_entries(id) ON DELETE RESTRICT, -- prevent deletion of species when it is referenced by a collection

    sling_male INT NOT NULL DEFAULT 0,
    sling_female INT NOT NULL DEFAULT 0,
    sling_unsexed INT NOT NULL DEFAULT 0,

    juvenile_male INT NOT NULL DEFAULT 0,
    juvenile_female INT NOT NULL DEFAULT 0,
    juvenile_unsexed INT NOT NULL DEFAULT 0,

    subadult_male INT NOT NULL DEFAULT 0,
    subadult_female INT NOT NULL DEFAULT 0,
    subadult_unsexed INT NOT NULL DEFAULT 0,

    adult_male INT NOT NULL DEFAULT 0,
    adult_female INT NOT NULL DEFAULT 0,
    adult_unsexed INT NOT NULL DEFAULT 0,

    custom_info VARCHAR(1000),
    featured_image_url VARCHAR(2048),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT uq_user_species UNIQUE (user_id, species_id), -- prevent a user from having multiple entries of the same species
    CONSTRAINT chk_counts_non_negative CHECK (
       sling_male >= 0 AND sling_female >= 0 AND sling_unsexed >= 0 AND
       juvenile_male >= 0 AND juvenile_female >= 0 AND juvenile_unsexed >= 0 AND
       subadult_male >= 0 AND subadult_female >= 0 AND subadult_unsexed >= 0 AND
       adult_male >= 0 AND adult_female >= 0 AND adult_unsexed >= 0
    )
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    deleted_by_sender BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_by_recipient BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_content_max_length CHECK (char_length(content) <= 2000)
);

CREATE INDEX idx_collections_species ON tarantula_collections(species_id);
CREATE INDEX idx_collections_user ON tarantula_collections(user_id);
CREATE INDEX idx_messages_recipient ON messages(recipient_id, deleted_by_recipient);
CREATE INDEX idx_messages_sender ON messages(sender_id, deleted_by_sender);